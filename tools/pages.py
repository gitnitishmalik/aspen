"""Build the inner pages (custom-homes.html, gallery.html, process.html) from index.html's shared parts.

  python -I tools/pages.py

The header, footer, corner buttons, chat and page-switch overlay are copied from index.html, so they
stay identical on every page. Each page's own content lives in pages-src/<name>.html. Edit those files
(or index.html's shared parts), then run this again. Don't edit the generated .html files directly.
"""
import os
import re

here = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
index = open(os.path.join(here, 'index.html'), encoding='utf-8').read()

PAGES = {
    'custom-homes': ('Custom Homes, Farmhouses & Barndominiums | Aspen Homes',
                     'Custom homes, luxury farmhouses, barndominiums and remodels from Aspen Homes, a family-owned builder in Hutto, TX.'),
    'gallery': ('Gallery | Aspen Homes',
                'Homes, rooms and build stages from Aspen Homes, a family-owned custom home builder in Hutto, TX.'),
    'process': ('Our Process & Build on Your Lot | Aspen Homes',
                'How Aspen Homes builds: design, plans and specifications, a fixed-price proposal, selections, the build and move-in.'),
}


def between(text, start, end, inclusive=True):
    a = text.index(start)
    b = text.index(end, a) + (len(end) if inclusive else 0)
    return text[a:b]


head = index[:index.index('</head>')]
# the hero's first frame is home-only: drop its comment and preloads (any 'as') from the inner pages
head = re.sub(r'\s*<!-- first hero frame[^>]*-->', '', head)
head = re.sub(r'\s*<link rel="preload"[^>]*href="frames/[^>]*>', '', head)
sprite = between(index, '  <!-- WhatsApp glyph', '</svg>\n') + '\n'
veil = between(index, '  <!-- Page switch', '</div>\n  </div>\n')
header = between(index, '  <header class="nav" id="nav">', '</header>\n')
footer = between(index, '  <footer class="foot">', '</footer>\n')
corner = between(index, '  <!-- WhatsApp, bottom left -->', '</section>\n')
lightbox = between(index, '  <!-- Photo viewer for the gallery -->', '</dialog>\n')

for name, (title, desc) in PAGES.items():
    main = open(os.path.join(here, 'pages-src', name + '.html'), encoding='utf-8').read().rstrip() + '\n'
    h = re.sub(r'<title>[^<]*</title>', f'<title>{title}</title>', head)
    h = re.sub(r'<meta name="description" content="[^"]*">', f'<meta name="description" content="{desc}">', h)
    h = h.replace('content="https://aspen-homes-concept.netlify.app/"', f'content="https://aspen-homes-concept.netlify.app/{name}.html"')
    page = (h + '</head>\n<body class="page page--' + name + '">\n' + sprite +
            '  <a class="skip" href="#main">Skip to content</a>\n\n' + veil + '\n' + header + '\n' +
            '  <main id="main">\n' + main + '  </main>\n\n' + footer + '\n' + corner + '\n' + lightbox + '\n' +
            '  <script src="main.js" defer></script>\n  <script src="motion.js" defer></script>\n'
            '  <script src="features.js" defer></script>\n  <script src="pages.js" defer></script>\n'
            '  <script src="chat.js" defer></script>\n</body>\n</html>\n')
    note = '<!-- Generated by tools/pages.py from pages-src/%s.html and index.html. Edit those, not this file. -->\n' % name
    page = page.replace('<!doctype html>\n', '<!doctype html>\n' + note, 1)   # the doctype must stay first
    with open(os.path.join(here, name + '.html'), 'w', encoding='utf-8', newline='\n') as fh:
        fh.write(page)
    print('wrote', name + '.html')
